"""Builds Ren's launcher icon, themed icon, notification icon and brand marks from the ren. logotype.

The logo is the name: lowercase "ren." with a volt full stop (ren's docs/brand.md § Logo). Its outlines are
``docs/design/ren-logotype.json``, copied from ren desktop's ``src/components/brand/logotype.ts``; the tile and the
R icon follow its ``RenMark.tsx`` and ``RenIcon.tsx``. From them this writes, as Android vector drawables:

- the adaptive icon layers ``ic_launcher_background`` (the volt tile), ``ic_launcher_foreground`` (the white logotype,
  also the splash icon) and ``ic_launcher_monochrome`` (the themed icon);
- ``ic_ren``, the status-bar and notification icon: the R of the Ren icon, one colour;
- ``ren_mark``, the square mark for the widgets: the white logotype on the volt tile;
- ``ren_logotype`` and ``ren_logotype_dot``, the letters and the full stop on one canvas, tinted where they are used
  (ink and volt);

plus ``build/icon-preview.svg`` for review.

Usage: python3 tools/build_icon.py [--check]  (from android/)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRAWABLE = ROOT / "app" / "src" / "main" / "res" / "drawable"
LOGOTYPE = ROOT.parent / "docs" / "design" / "ren-logotype.json"
PREVIEW = ROOT / "build" / "icon-preview.svg"

LOGO = json.loads(LOGOTYPE.read_text(encoding="utf-8"))
REN: str = LOGO["ren"]
DOT: str = LOGO["dot"]
WIDTH: float = LOGO["width"]
TOP: float = LOGO["top"]
HEIGHT: float = LOGO["height"]

# The tile's gradient (RenMark.tsx): blurple, lighter at the top left.
TILE = (("0", "#7A73FF"), ("0.55", "#5543FF"), ("1", "#4533D8"))
WHITE = "#FFFFFF"
# The tile's corner radius on RenMark's 48-unit box.
TILE_RADIUS = 10.8
# How much of the tile's width the logotype takes (RenMark's `fitted(0.8)`).
SHARE = 0.8


def fitted(box: float, share: float, offset: float = 0) -> tuple[float, float, float]:
    """The logotype in a [box] square at [offset]: [share] of the width, centred on its x-height (RenMark `fitted`)."""
    scale = box * share / WIDTH
    x = offset + (box - WIDTH * scale) / 2
    y = offset + box / 2 - (TOP + HEIGHT / 2) * scale
    return round(x, 3), round(y, 3), round(scale, 5)


def group(x: float, y: float, scale: float, paths: str) -> str:
    return (
        f'    <group android:translateX="{x:g}" android:translateY="{y:g}" android:scaleX="{scale:g}" android:scaleY="{scale:g}">\n'
        f"{paths}\n    </group>"
    )


def fill(d: str, color: str, indent: str = "        ") -> str:
    return f'{indent}<path android:fillColor="{color}" android:pathData="{d}" />'


def gradient(d: str, start: float, end: float) -> str:
    items = "".join(f'\n                <item android:offset="{o}" android:color="{c}" />' for o, c in TILE)
    return (
        f'    <path android:pathData="{d}">\n'
        '        <aapt:attr name="android:fillColor">\n'
        f'            <gradient android:type="linear" android:startX="{start:g}" android:startY="{start:g}" android:endX="{end:g}" android:endY="{end:g}">'
        f"{items}\n            </gradient>\n        </aapt:attr>\n    </path>"
    )


def rrect(size: float, r: float) -> str:
    return (
        f"M{r:g},0h{size - 2 * r:g}a{r:g},{r:g} 0 0 1 {r:g},{r:g}v{size - 2 * r:g}a{r:g},{r:g} 0 0 1 {-r:g},{r:g}"
        f"h{-(size - 2 * r):g}a{r:g},{r:g} 0 0 1 {-r:g},{-r:g}v{-(size - 2 * r):g}a{r:g},{r:g} 0 0 1 {r:g},{-r:g}z"
    )


def vector(body: str, width: float, height: float, viewport_width: float, viewport_height: float) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/build_icon.py from docs/design/ren-logotype.json; edit the tool, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        f'    android:width="{width:g}dp" android:height="{height:g}dp"\n'
        f'    android:viewportWidth="{viewport_width:g}" android:viewportHeight="{viewport_height:g}">\n'
        f"{body}\n</vector>\n"
    )


def logotype(color: str, box: float, offset: float = 0) -> str:
    """The whole logotype in one colour, fitted to a [box] square at [offset]."""
    return group(*fitted(box, SHARE, offset), fill(REN, color) + "\n" + fill(DOT, color))


# An adaptive icon layer is 108dp and the launcher shows its middle 72dp, so the tile is that middle square.
LAYER, SHOWN = 108.0, 72.0
INSET = (LAYER - SHOWN) / 2

BACKGROUND = vector(gradient(f"M0,0h{LAYER:g}v{LAYER:g}h{-LAYER:g}z", INSET, INSET + SHOWN), LAYER, LAYER, LAYER, LAYER)
FOREGROUND = vector(logotype(WHITE, SHOWN, INSET), LAYER, LAYER, LAYER, LAYER)
MONOCHROME = FOREGROUND
# The Ren icon (RenIcon.tsx): a capital R on the 24-unit icon grid, stroked like the app's line icons.
STATUS = vector(
    "\n".join(
        f'    <path android:strokeColor="{WHITE}" android:strokeWidth="2.25" android:strokeLineCap="round"'
        f' android:strokeLineJoin="round" android:pathData="{d}" />'
        for d in ("M7,20V4h6a4.5,4.5 0 0 1 0,9H7", "M12.5,13l5,7")
    ),
    24, 24, 24, 24,
)
MARK = vector(gradient(rrect(48, TILE_RADIUS), 0, 48) + "\n" + logotype(WHITE, 48), 48, 48, 48, 48)
# The logotype on its own advance box, 40dp to the em: the letters, and the full stop as its own layer.
EM = 40.0
LETTERS = vector(group(0, -TOP, 1, fill(REN, WHITE)), WIDTH * EM / 1000, HEIGHT * EM / 1000, WIDTH, HEIGHT)
FULL_STOP = vector(group(0, -TOP, 1, fill(DOT, WHITE)), WIDTH * EM / 1000, HEIGHT * EM / 1000, WIDTH, HEIGHT)

OUTPUTS = {
    "ic_launcher_background.xml": BACKGROUND,
    "ic_launcher_foreground.xml": FOREGROUND,
    "ic_launcher_monochrome.xml": MONOCHROME,
    "ic_ren.xml": STATUS,
    "ren_mark.xml": MARK,
    "ren_logotype.xml": LETTERS,
    "ren_logotype_dot.xml": FULL_STOP,
}


def preview() -> str:
    x, y, scale = fitted(SHOWN, SHARE, INSET)
    stops = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in TILE)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {LAYER:g} {LAYER:g}"><defs>'
        f'<linearGradient id="t" x1="{INSET:g}" y1="{INSET:g}" x2="{INSET + SHOWN:g}" y2="{INSET + SHOWN:g}" gradientUnits="userSpaceOnUse">{stops}'
        f'</linearGradient></defs><rect width="{LAYER:g}" height="{LAYER:g}" fill="url(#t)"/>'
        f'<g transform="translate({x} {y}) scale({scale})" fill="{WHITE}"><path d="{REN}"/><path d="{DOT}"/></g></svg>\n'
    )


def main() -> None:
    check = "--check" in sys.argv
    for name, text in OUTPUTS.items():
        path = DRAWABLE / name
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"{path} is stale; run tools/build_icon.py")
        else:
            path.write_text(text, encoding="utf-8")
    if not check:
        PREVIEW.parent.mkdir(parents=True, exist_ok=True)
        PREVIEW.write_text(preview(), encoding="utf-8")
        print(f"wrote {len(OUTPUTS)} drawables and {PREVIEW.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
