// src/cato (Cato, unmodified from catolabs.com) -> src/robot (ren's robot)
// usage: node scripts/gen-ren-robot.mjs [--check]
// Keeps Cato's geometry, rig, moves, props, decals and three.js renderer as they are; changes only what is listed
// here: Cato's blue becomes ren's volt (docs/brand.md: blurple 600 #5543FF, 300 #B3BDFF), the card colours become
// ren's tokens, and the names say Ren. --check verifies src/cato against SHA256SUMS and that src/robot is current.
import { createHash } from "node:crypto"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const cato = (name) => path.join(root, "src/cato", name)
const read = (name) => fs.readFileSync(cato(name), "utf8")
const check = process.argv.includes("--check")

for (const line of read("SHA256SUMS").trim().split("\n")) {
  const [sum, name] = line.split(/\s+/)
  const actual = createHash("sha256").update(fs.readFileSync(cato(name))).digest("hex")
  if (actual !== sum) throw new Error(`src/cato/${name} was edited; it must stay as it is in CatoWeb`)
}

/** Replaces every [from] with [to]; a pattern that is gone means Cato changed and this script must be read again. */
function swap(text, pairs) {
  for (const [from, to] of pairs) {
    if (!text.includes(from)) throw new Error("missing: " + from)
    text = text.split(from).join(to)
  }
  return text
}

const VOLT = [
  ["'#2E4BFF'", "'#5543FF'"], // the accent and paint materials
  ["'#B9C9FF'", "'#B3BDFF'"], // the LED material
  ["rgb(46,75,255)", "rgb(85,67,255)"], // decals, paints, the scene's second LED
  ["[185, 201, 255]", "[179, 189, 255]"], // the eyes and the LED at rest
]

const core = swap(read("timmy-core.js"), [
  ...VOLT,
  ["Yes, it is Cato.", "Yes, it is Ren."],
  ["export function createCatoCore(", "export function createRenCore("],
  // the letter -> viseme table the engine reads lines with, for lip sync from the app's word timings
  ["  moves: () => Object.keys(MOVES),\n", "  moves: () => Object.keys(MOVES),\n  letters: LETTER_VIS,\n"],
])

const types = swap(read("timmy-core.d.ts"), [
  ["/** Types for the generated Timmy engine (timmy-core.js). */", "/** Types for ren's robot engine (ren-core.js). */"],
  ["  moves(): string[];\n", "  moves(): string[];\n  letters: Readonly<Record<string, string>>;\n"],
]).replaceAll("Cato", "Ren")

const body = swap(read("CatoBody.tsx"), [
  ["from './timmy-core'", "from './ren-core'"],
  ['from "./timmy-core"', 'from "./ren-core"'],
  ["import './cato.css';", "import './ren-robot.css';"],
  ["rgba(11,16,51,", "rgba(11,12,23,"], // the contact shadow, in ren's ink
  // Cato's shader writes linear colour and leaves the sRGB curve to the bloom pass's output, so without that pass
  // (phones) the white shell drew grey and the accent dark. three's own chunk applies the curve only when the shader
  // draws straight to the screen, so both paths show the same white and volt.
  ["    gl_FragColor = vec4(x, 1.0);\n    return;", "    gl_FragColor = vec4(x, 1.0);\n    #include <colorspace_fragment>\n    return;"],
  ["  gl_FragColor = vec4(1.0 - exp(-x * 1.32), 1.0);\n}", "  gl_FragColor = vec4(1.0 - exp(-x * 1.32), 1.0);\n  #include <colorspace_fragment>\n}"],
]).replaceAll("Cato", "Ren")

const css = swap(read("cato.css"), [
  ["/* GENERATED by scripts/gen-cato-core.mjs from Timmy.html. Cato card + emote styles. */", "/* Card and emote styles of ren's robot, in ren's tokens. */"],
  ["--bg:#ffffff; --ink:#0b1033; --ink-2:#56607a;", "--bg:#ffffff; --ink:#0b0c17; --ink-2:#4a4c58;"],
  ["--accent:#2e4bff; --accent-ink:#ffffff;", "--accent:#5543ff; --accent-ink:#ffffff;"],
  ["--hud-line:rgba(11,16,51,.14); --tile:#eef2ff; --cy:#2e4bff; --ok:#1E9E6A; --amb:#C98A16; --rec:#E5484D;", "--hud-line:rgba(11,12,23,.09); --tile:#f5f6fe; --cy:#5543ff; --ok:#01B568; --amb:#E6C103; --rec:#EF2D4A;"],
  ["/* phones: Cato stands above the copy card, so the cards would cover it */\n@media (max-width:759px){.cato-host #gHud{display:none}}", "/* the cards carry Cato's sample lines, so the app shows only the robot and its emotes */\n.cato-host #gHud{display:none}"],
])

const header = (comment, from) => `${comment} Generated by scripts/gen-ren-robot.mjs from src/cato/${from}; edit the script, not this file. ${comment === "/*" ? "*/" : ""}`.trimEnd() + "\n"
const outputs = {
  "ren-core.js": header("//", "timmy-core.js") + core,
  "ren-core.d.ts": header("//", "timmy-core.d.ts") + types,
  "RenBody.tsx": header("//", "CatoBody.tsx") + body,
  "ren-robot.css": header("/*", "cato.css") + css,
}

for (const [name, text] of Object.entries(outputs)) {
  const file = path.join(root, "src/robot", name)
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) throw new Error(`src/robot/${name} is stale; run npm run gen:robot`)
  } else fs.writeFileSync(file, text)
}
console.log(check ? "robot is current" : `wrote ${Object.keys(outputs).join(", ")}`)
